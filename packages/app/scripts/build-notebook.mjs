// Bundles the notebook WebView entry (src/webview/notebook-main.tsx) into a single IIFE string
// that notebooks/NotebookView.tsx embeds in the native WebView HTML, the way build-canvas.mjs
// does for the canvas. The page view is DOM-only (ProseMirror + the SVG ink layer), so the
// native app hosts the same view the web app renders. Re-run after editing anything under
// src/notebooks/ (the .web view), packages/editor, or src/webview/notebook-main.tsx:
//   npm run build:notebook -w @companion/app
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const entry = resolve(root, "src/webview/notebook-main.tsx");
const out = resolve(root, "src/notebookBundle.generated.ts");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2019"],
  minify: true,
  write: false,
  jsx: "automatic",
  alias: { "react-native": "react-native-web" },
  resolveExtensions: [".web.tsx", ".web.ts", ".web.jsx", ".web.js", ".tsx", ".ts", ".jsx", ".js", ".json"],
  define: { "process.env.NODE_ENV": '"production"' },
});

const js = result.outputFiles[0].text;
const contents =
  `// AUTO-GENERATED by scripts/build-notebook.mjs — do not edit.\n` +
  `// Bundled notebook page view, embedded in the native WebView HTML by notebooks/NotebookView.tsx.\n` +
  `/* eslint-disable */\n` +
  `export const NOTEBOOK_JS = ${JSON.stringify(js)};\n`;
writeFileSync(out, contents);
console.log(`notebook bundle written: ${(js.length / 1024).toFixed(1)} kB → ${out}`);
